"""Tests for scripts/check_commit_msg.py (commit-message policy, D-008)."""

from __future__ import annotations

import importlib.util
import subprocess
import sys
from pathlib import Path
from types import ModuleType

import pytest

ROOT = Path(__file__).resolve().parents[1]


def _load() -> ModuleType:
    spec = importlib.util.spec_from_file_location(
        "check_commit_msg", ROOT / "scripts" / "check_commit_msg.py"
    )
    assert spec is not None
    assert spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


policy = _load()


@pytest.mark.parametrize(
    "message",
    [
        "fix: handle empty robots.txt\n",
        "feat(fetch): add budget\n\nCount every redirect hop against the budget.\n",
        "docs: notes\n\nBody text.\n\nSigned-off-by: A <a@example.com>\n",
        "chore: results\n\nFixtures were generated by the checks workflow.\n",
        "test: cover scissors\n\n# Please enter the commit message\n"
        "# ------------------------ >8 ------------------------\nReviewed-by: A\n",
        "fix: x\n\nNote the following.\nThis is prose: not a trailer block.\n",
    ],
)
def test_allowed(message: str) -> None:
    assert policy.check_message(message) == []


@pytest.mark.parametrize(
    ("message", "needle"),
    [
        ("feat: x\n\nBody.\n\nReviewed-by: A\n", "Reviewed-by"),
        ("feat: x\n\nBody.\n\nSigned-off-by: A\nAcked-by: B\n", "Acked-by"),
        ("feat: x\n\nHelped-by: A\n\nMore body.\n", "Helped-by"),
        ("feat: x\n\nBody.\n\nChange-Id: I1234\n", "Change-Id"),
        ("feat: x\n\nBody.\n\nRefs: #12\nSee-also: abc\n", "Refs"),
        ("feat: x\n\nBody.\n\nGenerated with SomeTool\n", "Generated with"),
        ("feat: x\n\n* Generated with [Tool](https://example.com)\n", "Generated with"),
    ],
)
def test_rejected(message: str, needle: str) -> None:
    problems = policy.check_message(message)
    assert problems, message
    assert any(needle in p for p in problems)


def test_empty_message_rejected() -> None:
    assert policy.check_message("# only a comment\n\n") == ["empty commit message"]


def test_duplicate_key_reported_once() -> None:
    message = "feat: x\n\nBody.\n\nReviewed-by: A\nReviewed-by: B\n"
    assert len(policy.check_message(message)) == 1


def test_subject_with_colon_alone_is_fine() -> None:
    assert policy.check_message("Fix: one-line subject\n") == []


def test_cli_exit_codes(tmp_path: Path) -> None:
    good = tmp_path / "good"
    bad = tmp_path / "bad"
    good.write_text("fix: fine\n", encoding="utf-8")
    bad.write_text("fix: no\n\nBody.\n\nReviewed-by: A\n", encoding="utf-8")
    script = str(ROOT / "scripts" / "check_commit_msg.py")
    assert subprocess.run([sys.executable, script, str(good)], check=False).returncode == 0
    result = subprocess.run(
        [sys.executable, script, str(bad)], check=False, capture_output=True, text=True
    )
    assert result.returncode == 1
    assert "Reviewed-by" in result.stderr
